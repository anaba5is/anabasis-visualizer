"""Rebuild the regional river overlay with `uv run scripts/build-map.py`."""

import argparse
import json
from pathlib import Path
from urllib.request import urlopen

from shapely.geometry import box, shape
from shapely.ops import linemerge


ROOT = Path(__file__).resolve().parents[1]
WEST, SOUTH, EAST, NORTH = 25, 29, 50, 44
# Give river lines a small margin beyond the atlas bounds.
CROP = box(WEST - 0.5, SOUTH - 0.5, EAST + 0.5, NORTH + 0.5)
RIVER_URL = (
    "https://raw.githubusercontent.com/nvkelso/natural-earth-vector/v5.1.2/geojson/"
    "ne_10m_rivers_lake_centerlines.geojson"
)
RIVER_NAMES = {
    "Al Furat": "Euphrates",
    "Aras": "Aras",
    "Byk Menderes": "Maeander",
    "Ceyhan": "Pyramus",
    "Dicle": "Tigris",
    "Euphrates": "Euphrates",
    "Firat": "Euphrates",
    "Murat": "Euphrates",
    "Tigris": "Tigris",
}


def read_rivers(folder):
    if folder:
        return json.loads((folder / "rivers_10m.geojson").read_bytes())["features"]
    with urlopen(RIVER_URL, timeout=45) as response:
        return json.load(response)["features"]


def line_strings(geometry):
    if geometry.is_empty:
        return
    if geometry.geom_type == "LineString":
        yield geometry
    elif hasattr(geometry, "geoms"):
        for part in geometry.geoms:
            yield from line_strings(part)


def points(coordinates):
    return [[round(x, 4), round(y, 4)] for x, y in coordinates]


def waterways(records):
    by_river = {}
    for feature in records:
        name = RIVER_NAMES.get(feature["properties"]["name"])
        if not name:
            continue
        geometry = shape(feature["geometry"])
        if geometry.intersects(CROP):
            by_river.setdefault(name, []).extend(line_strings(geometry.intersection(CROP)))

    for name, segments in sorted(by_river.items()):
        lines = [points(line.coords) for line in line_strings(linemerge(segments))]
        yield {"name": name, "lines": lines}


def write_rivers(folder):
    rivers = list(waterways(read_rivers(folder)))
    with (ROOT / "assets/map-geometry.mjs").open("w", encoding="utf-8") as target:
        target.write("// Generated by scripts/build-map.py from Natural Earth public-domain vectors.\n")
        # Older cached map-data modules still re-export these names.
        target.write("export const land = [];\nexport const lakes = [];\n")
        target.write("\nexport const rivers = [\n")
        for item in rivers:
            target.write(f"  {json.dumps(item, separators=(',', ':'))},\n")
        target.write("];\n")


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--sources", type=Path, help="Read previously downloaded source files from this directory")
    args = parser.parse_args()
    write_rivers(args.sources)
