"""Rebuild the local Natural Earth basemap with `uv run scripts/build-map.py`."""

import argparse
import json
import math
from io import BytesIO
from pathlib import Path
from urllib.request import urlopen
from zipfile import ZipFile

from PIL import Image
from shapely.geometry import box, shape
from shapely.ops import linemerge


ROOT = Path(__file__).resolve().parents[1]
WEST, SOUTH, EAST, NORTH = 25, 29, 50, 44
# Keep the edges beyond the displayed frame so outlines do not trace its border.
CROP = box(WEST - 0.5, SOUTH - 0.5, EAST + 0.5, NORTH + 0.5)
VECTOR_URL = "https://raw.githubusercontent.com/nvkelso/natural-earth-vector/v5.1.2/geojson"
RELIEF_URL = "https://naciscdn.org/naturalearth/50m/raster/SR_50M.zip"
LAKES = {"Lake Sevan", "Lake Tuz", "Lake Urmia", "Lake Van", "Dead Sea", "Sea of Galilee"}
RIVER_NAMES = {
    "Al Furat": "Euphrates",
    "Aras": "Aras",
    "Byk Menderes": "Maeander",
    "Ceyhan": "Pyramus",
    "Dicle": "Tigris",
    "Euphrates": "Euphrates",
    "Firat": "Euphrates",
    "Murat": "Euphrates",
    "Tigris": "Tigris",
}


def get_bytes(folder, filename, url):
    if folder:
        return (folder / filename).read_bytes()
    with urlopen(url, timeout=45) as response:
        return response.read()


def features(folder, filename, layer):
    data = get_bytes(folder, filename, f"{VECTOR_URL}/{layer}.geojson")
    return json.loads(data)["features"]


def geometry_parts(geometry, kind):
    if geometry.is_empty:
        return
    if geometry.geom_type == kind:
        yield geometry
    elif hasattr(geometry, "geoms"):
        for part in geometry.geoms:
            yield from geometry_parts(part, kind)


def points(coordinates):
    return [[round(x, 4), round(y, 4)] for x, y in coordinates]


def polygons(records):
    for feature in records:
        geometry = shape(feature["geometry"])
        if not geometry.intersects(CROP):
            continue
        trimmed = geometry.intersection(CROP).simplify(0.009, preserve_topology=True)
        for polygon in geometry_parts(trimmed, "Polygon"):
            if polygon.area >= 0.0005:
                yield [points(polygon.exterior.coords), *[points(ring.coords) for ring in polygon.interiors]]


def waterways(records):
    by_river = {}
    for feature in records:
        name = RIVER_NAMES.get(feature["properties"]["name"])
        if not name:
            continue
        geometry = shape(feature["geometry"])
        if geometry.intersects(CROP):
            by_river.setdefault(name, []).extend(geometry_parts(geometry.intersection(CROP), "LineString"))

    for name, segments in sorted(by_river.items()):
        lines = [points(line.coords) for line in geometry_parts(linemerge(segments), "LineString")]
        yield {"name": name, "lines": lines}


def write_layers(folder):
    land = features(folder, "land.geojson", "ne_50m_land")
    lakes = features(folder, "lakes.geojson", "ne_50m_lakes")
    rivers = features(folder, "rivers_10m.geojson", "ne_10m_rivers_lake_centerlines")
    layers = {
        "land": polygons(land),
        "lakes": polygons(feature for feature in lakes if feature["properties"]["name"] in LAKES),
        "rivers": waterways(rivers),
    }

    with (ROOT / "assets/map-geometry.mjs").open("w", encoding="utf-8") as target:
        target.write("// Generated by scripts/build-map.py from Natural Earth public-domain vectors.\n")
        for name, layer in layers.items():
            target.write(f"\nexport const {name} = [\n")
            for item in layer:
                target.write(f"  {json.dumps(item, separators=(',', ':'))},\n")
            target.write("];\n")


def write_relief(folder):
    archive = get_bytes(folder, "shaded-relief.zip", RELIEF_URL)
    with ZipFile(BytesIO(archive)) as source:
        scale, _, _, negative_scale, x, y = map(float, source.read("SR_50M.tfw").split())
        x_edge = x - scale / 2
        y_edge = y - negative_scale / 2
        left, right = (round((lon - x_edge) / scale) for lon in (WEST, EAST))
        top, bottom = (round((lat - y_edge) / negative_scale) for lat in (NORTH, SOUTH))
        with Image.open(BytesIO(source.read("SR_50M.tif"))) as image:
            gray = image.crop((left, top, right, bottom)).convert("L")

    # The source uses gray level 206 for water. Convert relief to neutral ink so
    # the same transparent layer can be placed over differently colored maps.
    palette = []
    for level in range(256):
        delta = level - 206
        tone = 255 if delta > 0 else 27
        alpha = min(205, round(math.pow(abs(delta), 1.14) * 1.6))
        palette.append((tone, tone, tone, alpha))

    relief = Image.new("RGBA", gray.size)
    relief.putdata([palette[value] for value in gray.tobytes()])
    relief.save(ROOT / "assets/anabasis-relief.webp", quality=84, method=6)


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--sources", type=Path, help="Read previously downloaded source files from this directory")
    args = parser.parse_args()
    write_layers(args.sources)
    write_relief(args.sources)
